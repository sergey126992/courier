<?php

declare(strict_types=1);

namespace App\Services\Events;

/**
 * Итог обработки события в Inbox (FR-NTF-133, FR-NTF-134).
 *
 * Значение нужно вызывающему коду и журналу: «обработано» означает, что эффект
 * выполнен и отметка записана, а «пропущено» — что событие этим обработчиком
 * уже обработано и второго эффекта нет.
 */
enum InboxResult: string
{
    /**
     * Эффект выполнен, отметка записана в той же транзакции.
     */
    case Processed = 'processed';

    /**
     * Событие уже обработано этим обработчиком: эффект не выполняется.
     */
    case Skipped = 'skipped';

    /**
     * Обработка пропущена как повторная или параллельная.
     */
    public function isSkipped(): bool
    {
        return $this === self::Skipped;
    }
}
