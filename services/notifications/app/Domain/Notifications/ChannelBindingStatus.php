<?php

declare(strict_types=1);

namespace App\Domain\Notifications;

/**
 * Состояние привязки канала (ЧТЗ 5.2, FR-NTF-411…417).
 *
 * Отдельной колонки статуса нет: состояние вычисляется по `verified_at`,
 * `revoked_at` и наличию действующего токена привязки, поэтому значение —
 * производное и живёт в домене, а не в базе.
 */
enum ChannelBindingStatus: string
{
    /**
     * Привязки канала у пользователя нет (ЧТЗ 5.2).
     */
    case Absent = 'absent';

    /**
     * Токен выпущен и ещё действует, активной привязки нет (ЧТЗ 5.2).
     */
    case Pending = 'pending';

    /**
     * Активная привязка с заполненным моментом подтверждения (ЧТЗ 5.2).
     */
    case Verified = 'verified';

    /**
     * История привязок есть, активной строки нет (ЧТЗ 5.2).
     */
    case Revoked = 'revoked';
}
