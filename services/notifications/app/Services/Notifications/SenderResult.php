<?php

declare(strict_types=1);

namespace App\Services\Notifications;

/**
 * Итог одного прохода поллера отправки (FR-NTF-272, FR-NTF-274).
 *
 * Счётчики нужны для вывода команды и для тестов; идентификаторов
 * получателей, адресов и текстов сообщений здесь нет.
 */
final class SenderResult
{
    /**
     * Сколько уведомлений взято в обработку.
     */
    public int $processed = 0;

    /**
     * Сколько уведомлений успешно отправлено.
     */
    public int $sent = 0;

    /**
     * Сколько уведомлений осталось с инфраструктурной ошибкой (повтор).
     */
    public int $error = 0;

    /**
     * Сколько уведомлений окончательно не отправлено.
     */
    public int $failed = 0;

    /**
     * Адресная отправка не нашла уведомление.
     */
    public bool $missing = false;
}
