<?php

declare(strict_types=1);

namespace App\Services\Notifications\Telegram;

/**
 * Итог обработки одного апдейта бота (FR-NTF-442).
 *
 * Значение нужно команде и вебхуку для счётчиков: привязка создана,
 * отправлена подсказка, токен отклонён или апдейт к делу не относится.
 * Персональных данных в значении нет.
 */
enum TelegramUpdateResult: string
{
    /**
     * Действующий токен подтвердил привязку чата.
     */
    case Linked = 'linked';

    /**
     * Отправлена подсказка: токена нет.
     */
    case Prompted = 'prompted';

    /**
     * Отправлена подсказка: токен недействителен или истёк.
     */
    case Rejected = 'rejected';

    /**
     * Апдейт не относится к привязке и проигнорирован.
     */
    case Ignored = 'ignored';
}
