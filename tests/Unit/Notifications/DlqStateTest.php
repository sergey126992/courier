<?php

declare(strict_types=1);

use App\Domain\Notifications\DlqState;

/*
|--------------------------------------------------------------------------
| Тон бейджа состояния очереди необработанных (ЧТЗ 5.2, FR-UI-176)
|--------------------------------------------------------------------------
|
| Административная страница показывает тон для каждого состояния, а не
| выводит цвет по месту. Тест закрывает все ветки соответствия.
|
*/

it('отдаёт тон бейджа для каждого состояния очереди', function (): void {
    expect(DlqState::Open->tone())->toBe('error')
        ->and(DlqState::Replayed->tone())->toBe('queued')
        ->and(DlqState::Resolved->tone())->toBe('sent');
});
